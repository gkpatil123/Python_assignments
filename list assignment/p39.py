# 39. Create a nested list and access inner elements.

matrix = [
    [10, 20, 30],
    [40, 50, 60],
    [70, 80, 90]
]
print("Nested list (matrix):", matrix)

print("Element at row 0, column 1:", matrix[0][1])
print("Element at row 1, column 2:", matrix[1][2])
print("Element at row 2, column 0:", matrix[2][0])
